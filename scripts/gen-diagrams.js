const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
// 글자 폭 어림: 한글은 글자 크기만큼, 나머지는 절반 남짓. 넘치면 경고만 한다 (Pretendard 기준, 대략값).
const est = (s, size) => [...s].reduce((n, ch) => n + (ch.charCodeAt(0) > 0x1100 ? size * 0.98 : size * 0.58), 0);
let current = "";
function fit(s, size, room) {
  if (est(s, size) > room) console.warn(`  ! ${current}: "${s}" 가 칸(${room}px)보다 넓다 (~${Math.round(est(s, size))}px)`);
}

const T = (x, y, s, cls = "t", anchor = "middle") => `<text x="${x}" y="${y}" text-anchor="${anchor}" class="${cls}">${esc(s)}</text>`;

// 상자: 제목 한 줄 + 부제 여러 줄을 세로 가운데에 둔다.
function box(x, y, w, h, title, subs = [], { key = false, cls } = {}) {
  const big = key;
  const tcls = big ? "tb" : "t";
  fit(title, big ? 16 : 14, w - 14);
  subs.forEach((s) => fit(s, 12, w - 14));
  const cx = x + w / 2;
  const block = (big ? 16 : 14) + subs.length * 18;
  const ty = y + h / 2 - block / 2 + (big ? 13 : 12);
  const r = key ? 14 : 12;
  let out = `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" class="${cls || (key ? "key" : "box")}"/>`;
  out += T(cx, ty, title, tcls);
  subs.forEach((s, i) => (out += T(cx, ty + 21 + i * 18, s, "s")));
  return out;
}
function chip(x, y, w, s, h = 30) {
  fit(s, 12.5, w - 14);
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${h / 2}" class="chip"/>` + T(x + w / 2, y + h / 2 + 4.5, s, "c");
}
function zone(x, w, label, y = 22, h = 206) {
  fit(label, 11.5, w - 20);
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="14" class="zone"/>` + T(x + 14, y + 19, label, "zl", "start");
}
const arw = (d, both = false) =>
  `<path d="${d}" class="arw"${both ? ' marker-start="url(#h)"' : ""} marker-end="url(#h)"/>`;
const ln = (d) => `<path d="${d}" class="ln"/>`;
const no = (d) => `<path d="${d}" class="no"/>`;
const L = (x, y, s, anchor = "middle") => T(x, y, s, "al", anchor);
const S = (x, y, s, anchor = "middle") => T(x, y, s, "s", anchor);
const X = (cx, cy, r = 6) => `<path d="M${cx - r} ${cy - r} L${cx + r} ${cy + r} M${cx + r} ${cy - r} L${cx - r} ${cy + r}" class="x"/>`;

function svg(aria, body, h = H) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${h}" role="img"
     aria-label="${esc(aria)}">
  <style>${STYLE}
  </style>
  <defs>
    <marker id="h" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M0 0 L10 5 L0 10 z" class="dot"/>
    </marker>
  </defs>
  ${body}
</svg>
`;
}

